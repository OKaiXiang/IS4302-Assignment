import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const deploymentFile = path.join(
  root,
  "ignition",
  "deployments",
  "chain-31337",
  "deployed_addresses.json",
);

if (!fs.existsSync(deploymentFile)) {
  console.error(`Deployment file not found: ${deploymentFile}`);
  console.error("Start Hardhat node and deploy OpenAid first:");
  console.error("  npx hardhat ignition deploy ignition/modules/OpenAid.ts --network localhost");
  process.exit(1);
}

const deployed = JSON.parse(fs.readFileSync(deploymentFile, "utf8"));
const factoryAddress = deployed["OpenAidModule#CharityFactory"];

if (!factoryAddress) {
  console.error("Could not find OpenAidModule#CharityFactory in deployed_addresses.json");
  console.error("Available keys:", Object.keys(deployed));
  process.exit(1);
}

const output = `// Generated by npm run frontend:config\nwindow.OPENAID_CONFIG = {\n  factoryAddress: \"${factoryAddress}\",\n};\n`;
const outputPath = path.join(root, "frontend", "config.js");
fs.writeFileSync(outputPath, output);
console.log(`Frontend configured with factory: ${factoryAddress}`);
console.log(`Wrote ${outputPath}`);
